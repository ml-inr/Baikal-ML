def formula(tex: str, name: str, fontsize: float = 13.5) -> Image:
    """Рендер формулы mathtext'ом и вставка картинкой (масштаб 1:1 по кеглю)."""
    FORMULAS.mkdir(parents=True, exist_ok=True)
    path = FORMULAS / f"{name}.png"
    if not path.exists():
        fig = plt.figure(figsize=(0.1, 0.1))
        fig.text(0, 0, f"${tex}$", fontsize=fontsize, color="black")
        fig.savefig(path, dpi=DPI, bbox_inches="tight", pad_inches=0.02,
                    transparent=True)
        plt.close(fig)
    from PIL import Image as PILImage
    with PILImage.open(path) as im:
        w, h = im.size
    scale = 72.0 / DPI
    return Image(str(path), width=w * scale, height=h * scale)


def fig(name: str, caption: str, width_mm: float = 165) -> KeepTogether:
    from PIL import Image as PILImage
    with PILImage.open(FIGDIR / name) as im:
        w, h = im.size
    width = width_mm * mm
    img = Image(str(FIGDIR / name), width=width, height=width * h / w)
    return KeepTogether([img, Paragraph(caption, S["caption"])])


