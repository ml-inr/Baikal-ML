class Doc(BaseDocTemplate):
    def __init__(self, path: str, **kw):
        BaseDocTemplate.__init__(self, path, **kw)
        frame = Frame(22 * mm, 20 * mm, 167 * mm, 250 * mm, id="body")
        self.addPageTemplates([
            PageTemplate(id="title", frames=[Frame(22 * mm, 60 * mm, 167 * mm, 150 * mm,
                                                   id="t")], onPage=self._decor),
            PageTemplate(id="body", frames=[frame], onPage=self._decor),
        ])
        self._counters = {"H1": 0, "H2": 0}

    def _decor(self, canvas, doc):
        canvas.saveState()
        canvas.setFont("DejaVu", 7.5)
        canvas.setFillColor(GREY)
        if doc.page > 1:
            canvas.drawCentredString(A4[0] / 2, 12 * mm,
                                     f"DANN: обход дискриминатора · конспект · стр. {doc.page}")
        canvas.restoreState()

    def afterFlowable(self, flowable):
        if not isinstance(flowable, Paragraph):
            return
        style = flowable.style.name
        if style in ("H1", "H2"):
            text = flowable.getPlainText()
            level = 0 if style == "H1" else 1
            self._counters[style] += 1
            key = f"{style}-{self._counters[style]}"
            self.canv.bookmarkPage(key)
            self.canv.addOutlineEntry(text, key, level=level, closed=(level == 0))
            if COLLECT and text != "Содержание":
                PAGE_MAP.append((level, text, self.page))


# Содержание собирается в два явных прохода: сначала запоминаем страницы
# заголовков, потом подставляем их в оглавление. Автоматический multiBuild на
# этом документе не сходится (плавающая разбивка страниц), а два прохода с
# фиксированной страницей-заглушкой дают точные номера.
PAGE_MAP: list[tuple[int, str, int]] = []
COLLECT = True


def toc_flowables() -> list:
    if not PAGE_MAP:
        return [Spacer(1, 232 * mm)]
    rows = []
    for level, text, page in PAGE_MAP:
        style = S["body"] if level == 0 else st("TOC2", fontSize=9.5, leading=15,
                                                leftIndent=13, textColor=GREY,
                                                spaceAfter=0, alignment=0)
        rows.append([Paragraph(text, style), Paragraph(str(page), S["note"])])
    t = Table(rows, colWidths=[150 * mm, 15 * mm])
    t.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("ALIGN", (1, 0), (1, -1), "RIGHT"),
        ("TOPPADDING", (0, 0), (-1, -1), 0.5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 0.5),
        ("LEFTPADDING", (0, 0), (-1, -1), 0),
    ]))
    return [t]


